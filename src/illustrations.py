def render_illustration(item):
    key = item['key']
    src = f'assets/screenshots/{key}.png'
    title, caption = escape(item['title']), escape(item['caption'])
    notes = '<ul class="shot-notes">' + ''.join(f'<li>{escape(text)}</li>' for text in item['notes']) + '</ul>' if item['notes'] else ''
    return f'''<figure class="screenshot" id="figure-{key}"><a class="screenshot-link" href="{src}" target="_blank" rel="noopener" aria-label="Увеличить: {title}"><img src="{src}" alt="{title}" width="{item['width']}" height="{item['height']}" loading="lazy" decoding="async"><span class="zoom-hint">Увеличить ↗</span></a><figcaption><strong class="shot-title">{title}</strong><p class="shot-caption">{caption}</p>{notes}</figcaption></figure>'''


def illustrated_body(chapter):
    body = chapter['body']
    for item in ILLUSTRATIONS:
        if item['chapter'] != chapter['id']:
            continue
        figure = render_illustration(item)
        if item['before']:
            marker = f'<h2>{item["before"]}</h2>'
            if marker not in body:
                raise ValueError(f'Missing illustration placement: {chapter["id"]} / {item["before"]}')
            body = body.replace(marker, figure + marker, 1)
        else:
            body += figure
    return body
